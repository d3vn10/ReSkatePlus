// The client physics world's bodies, as the park editor's surface probe and the game's ghosting
// of placed objects use them (read 2026-10-21). A body is a handle {world, index | generation << 32}
// (park_editor_surface.h's SurfaceBody); the world's store is at world + 0x00. In the store:
//   +0x0000  u32 per body: its owner's index. +0x000: a bit per owner, clear for an ECS entity;
//            +0x000: a u64 per owner, the entity id for an ECS owner (body_entity, 0x3d09a20).
//   +0x000   a bit per body: a ghost, which skaters go through (the Build Kit's walk-through
//            objects, 0x708de0 -> 0x25d3610 for each body of the object).
// ghost_body(const body*) sets a body's ghost bit and tells the world when it changed;
// solid_body(const body*) clears it (0x708be0 -> 0x25d3170). The game's ghosting also sets the
// object's main body's bit at +0x000 (main_ghost 0x25d3360, which tells the world too) and its
// solid side clears it (main_solid 0x25d2e90). Client thread.
// rigid_bodies.h reads the same store for the bodies plugins own (Extension/World/owned_bodies.cpp)
// and calls what this header calls a body a shape: its store + 0x000 maps each one to the rigid
// body that carries it. body_owner_offset is indexed by that same handle, so it holds each shape's
// owner slot.
